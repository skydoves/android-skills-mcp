#!/usr/bin/env node
// Regenerates docs/skills-catalog.md from the upstream skills checkout.
//
// The catalog used to be hand-maintained, which meant it silently rotted every
// time upstream added or removed a skill. Generating it keeps the published docs
// true to whatever `.skills-commit` is pinned to.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');

// Resolve @android-skills/core via its built dist file so this works from any cwd.
const { loadSkills } = await import(resolve(__dirname, '../packages/core/dist/index.js'));

const { values } = parseArgs({
  options: {
    'skills-dir': { type: 'string', default: resolve(repoRoot, 'skills') },
    out: { type: 'string', default: resolve(repoRoot, 'docs/skills-catalog.md') },
  },
});

const skillsDir = values['skills-dir'];
if (!existsSync(skillsDir)) {
  console.error(`Skills directory not found: ${skillsDir}`);
  console.error('Run `pnpm sync:skills` first.');
  process.exit(1);
}

const skills = await loadSkills(skillsDir);
if (skills.length === 0) {
  console.error(`No SKILL.md files found under ${skillsDir}`);
  process.exit(1);
}

// Frontmatter descriptions lead with a one-sentence summary and continue with the
// detail; splitting them keeps the two-paragraph shape the catalog has always had.
function splitLead(description) {
  const text = description.replace(/\s+/g, ' ').trim();
  const m = text.match(/^(.+?[.!?])\s+(?=[A-Z`])(.+)$/s);
  return m ? [m[1], m[2]] : [text];
}

const commitFile = resolve(repoRoot, '.skills-commit');
const sha = existsSync(commitFile) ? readFileSync(commitFile, 'utf8').trim() : '';
const short = sha.slice(0, 7);

const byCategory = new Map();
for (const skill of skills) {
  const list = byCategory.get(skill.category) ?? [];
  list.push(skill);
  byCategory.set(skill.category, list);
}
const categories = [...byCategory.keys()].sort();

const lines = [
  '# Skill Catalog',
  '',
  '<!-- Generated by scripts/build-skills-catalog.mjs. Do not edit by hand; run `pnpm docs:catalog`. -->',
  '',
  `The snapshot bundled in both packages contains ${skills.length} skills across ${categories.length} categories, taken from upstream \`android/skills\`` +
    (sha
      ? ` at [\`${short}\`](https://github.com/android/skills/commit/${sha}).`
      : '.') +
    ' Each category heading below is also the value accepted by the `category` filter on the `list_skills` MCP tool.',
  '',
];

for (const category of categories) {
  lines.push(`## ${category}`, '');
  for (const skill of byCategory.get(category).sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`### \`${skill.name}\``, '');
    for (const paragraph of splitLead(skill.description)) lines.push(paragraph, '');
  }
}

const out = resolve(process.cwd(), values.out);
writeFileSync(out, `${lines.join('\n').trimEnd()}\n`);
console.log(`Wrote ${skills.length} skills in ${categories.length} categories → ${out}`);
